#!/usr/bin/env python3
"""Writes Sources/MediaEngine/Acknowledgements.generated.swift (LIC-4): the third-party components of the shipped binaries as
structured data, with versions, source URLs and checksums from third_party/sources.lock and the licence texts from the pinned
source archives (build/src, fetched by scripts/fetch-sources.sh). Run after changing a pin; a test fails when the file is stale.

usage: scripts/gen-acknowledgements.py [--check]     (--check only compares and exits 1 when the file would change)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "Sources/MediaEngine/Acknowledgements.generated.swift"


def lock():
    entries = {}
    for line in (ROOT / "third_party/sources.lock").read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        entries[fields[0]] = {"version": fields[1], "url": fields[2], "sha256": fields[3]}
    return entries


def literal(text):
    """A Swift raw multi-line string literal that cannot be broken out of."""
    hashes = "#"
    while ('"""' + hashes) in text or ("\\" + hashes) in text:
        hashes += "#"
    return f'{hashes}"""\n{text.rstrip()}\n"""{hashes}'


def quoted(text):
    return "nil" if text is None else '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    pins = lock()
    components = json.loads((ROOT / "third_party/components.json").read_text())
    body = []
    for component in components:
        pin = pins[component["lock"]]
        text_path = ROOT / "build/src" / f"{component['lock']}-{pin['version']}" / component["licenseFile"]
        if not text_path.exists():
            sys.exit(f"missing {text_path}: run scripts/fetch-sources.sh")
        text = text_path.read_text(errors="replace").replace("\t", "    ")
        text = "\n".join(line.rstrip() for line in text.splitlines())
        body.append(f"""        Acknowledgement(
            id: "{component['id']}", name: {quoted(component['name'])}, version: "{pin['version']}",
            usedFor: {quoted(component['usedFor'])},
            license: "{component['license']}", copyright: {quoted(component['copyright'])}, requiredNotice: {quoted(component['notice'])},
            sourceURL: URL(string: "{pin['url']}")!, sha256: "{pin['sha256']}",
            isReplaceable: {str(component['replaceable']).lower()}, includedIn: .{component['profile']},
            licenseText: {literal(text)}),""")
    content = (
        "// Generated by scripts/gen-acknowledgements.py from third_party/components.json and third_party/sources.lock. Do not edit.\n"
        "import Foundation\n\n"
        "extension MediaEngine {\n"
        "    static let allAcknowledgements: [Acknowledgement] = [\n" + "\n".join(body) + "\n    ]\n}\n")
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == content else 1)
    OUT.write_text(content)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(components)} components, {len(content) // 1024} KB)")


if __name__ == "__main__":
    main()
