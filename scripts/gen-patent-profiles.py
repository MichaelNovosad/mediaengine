#!/usr/bin/env python3
"""Writes docs/PATENT_PROFILES.md (LIC-6): every codec of each profile with its royalty status, generated from profiles/*.json so
the document cannot drift from what is compiled in. A decoder, encoder or demuxer without a status entry fails the run.

usage: scripts/gen-patent-profiles.py [--check]     (--check: exit 1 when the file is stale or an entry has no status)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/PATENT_PROFILES.md"
PROFILES = ["core", "extended", "licensedAudio"]

# FFmpeg component name -> key of codecStatus in the profile files.
ALIASES = {
    "mp3float": "mp3", "mp2float": "mp2", "mpegaudio": "mp3", "mpegvideo": "mpeg2video", "mpeg4video": "mpeg4",
    "msmpeg4v1": "msmpeg4", "msmpeg4v2": "msmpeg4", "msmpeg4v3": "msmpeg4", "wmv1": "wmv", "wmv2": "wmv",
    "h263i": "h263", "h263p": "h263", "vp6f": "vp6", "vp6a": "vp6", "rv10": "rv", "rv20": "rv", "rv30": "rv", "rv40": "rv",
    "adpcm_ms": "adpcm", "adpcm_ima_wav": "adpcm", "libdav1d": "av1", "aac_latm": "aac", "aac_at": "aac_at", "alac_at": "alac",
    "subrip": "subtitles", "ass": "subtitles", "ssa": "subtitles", "webvtt": "subtitles", "mov_text": "subtitles",
    "dvdsub": "subtitles", "pgssub": "subtitles", "dvbsub": "subtitles", "srt": "subtitles", "vobsub": "subtitles",
    "sup": "subtitles", "mpegts": "container", "mpegps": "container", "matroska": "container", "mov": "container",
    "ogg": "container", "wav": "container", "avi": "avi", "flv": "flv", "rm": "rm", "asf": "asf",
}
GENERIC = ["pcm_", "adpcm_"]


def key_for(name, status):
    candidates = [name, ALIASES.get(name, name)]
    if name.startswith("pcm_"):
        candidates.append("pcm")
    return next((c for c in candidates if c in status), None)


def load():
    return {name: json.loads((ROOT / "profiles" / f"{name}.json").read_text()) for name in PROFILES}


HEADER = """# Patent and licensing profiles

**Draft for a lawyer's review. This document is not legal advice and states no legal conclusion.** It is generated by
`scripts/gen-patent-profiles.py` from `profiles/*.json` (the same files that generate the FFmpeg build flags), so it lists
exactly what is compiled into each profile. Strategy and sources: `docs/RESEARCH.md` section 3.

## Who is responsible

- The engine is built on FFmpeg under the LGPL (a copyright licence). **Patents are separate and local to a country.** Neither
  FFmpeg nor this package grants patent licences. **The integrator (the app publisher) is responsible for the patent licences
  of every profile and codec it enables and distributes**, in every territory where the app is available.
- A profile is a separate binary variant (`FFmpegLGPL.xcframework` is `core`, `FFmpegLGPL-extended.xcframework` is
  `core` + `extended`). An app that links only `core` contains none of the software decoders listed under `extended` and
  `licensedAudio`. `MediaInfo.requiredProfile` tells the host which profile a file needs, so it can gate the feature.
- The engine never decides what is allowed: the host app does.

## Launch default

1. **Apple's decoders decode** whatever they cover (H.264, HEVC, AAC, AC-3, E-AC-3, ALAC, MP3, ProRes, hardware AV1 where the
   chip has it). The remux path only repackages bytes and converts lossless audio.
2. **Our own decoders only for royalty-free or expired codecs** (the `extended` profile; statuses below).
3. **Container work needs no codec licence** (reading and remuxing Matroska, AVI, FLV, RealMedia, MPEG-TS and so on); the
   containers of old formats are still reported as needing `extended` so a host can offer them as a paid feature.
4. **Off by default and not built:** VC-1 and WMV3 (held back until cleared), DTS, DTS-HD and Dolby TrueHD (`licensedAudio`,
   not part of the shipped binaries), Dolby Vision profile 7 conversion, a software H.264 decoder (so no Hi10P), Windows Media
   Audio and RealAudio (the decoders are left out of version 1).
5. A module is switched on only after a lawyer's opinion and once there is revenue to pay a licensor who asks.

## Trademarks

Do not use Dolby, Dolby Vision, Dolby Atmos, DTS, DTS-HD, TrueHD, Apple, AirPlay or FFmpeg marks or logos as branding of your
app or of this package. Plain descriptive mentions ("plays files with Dolby Digital audio") need review by a lawyer. The text
required by the licences is in `third_party/NOTICES.md` and `MediaEngine.acknowledgements`.

## Status vocabulary

| Status | Meaning |
|---|---|
| `apple-decoder` | no software decoder in our binary; the system decodes it under Apple's licences |
| `royalty-free` | published as royalty-free by its owner; patent-pool claims by third parties have been reported (see the note) |
| `expired` | the patents are reported to have expired (sources in `docs/RESEARCH.md`; to be confirmed by the lawyer) |
| `open`, `no-patents` | open formats and old formats without known live claims |
| `apple-licensed` | encoding done by Apple's AudioToolbox |
| `needs-review` | the status is not established; the decoder is in the profile and is a candidate for removal |
| `needs-clearance` | live licensing programmes; the decoder is **not** in any shipped binary |
| `container` | a container or demuxer: no codec licence; grouped with `extended` for gating only |
"""


def build(profiles):
    lines = [HEADER]
    problems = []
    for name in PROFILES:
        profile = profiles[name]
        status = profile["codecStatus"]
        ffmpeg = profile["ffmpeg"]
        lines += [f"## Profile `{name}`", "", profile["description"], ""]
        listed = set()
        rows = []
        # Decoders and encoders must have a status. Demuxers, muxers and parsers only read, cut or write containers and bitstreams
        # (container work needs no codec licence), so they are listed but not required to have one.
        for kind in ("decoders", "encoders"):
            for component in ffmpeg.get(kind, []):
                key = key_for(component, status)
                if key is None:
                    problems.append(f"{name}: {kind[:-1]} '{component}' has no entry in codecStatus")
                    continue
                listed.add(key)
        for key in sorted(status):
            entry = status[key]
            in_build = "yes" if key in listed or key in ("subtitles",) else "no (not compiled in)"
            rows.append(f"| {key} | {entry['status']} | {in_build} | {entry.get('note', '')} |")
        lines += ["| Codec or format | Status | In this profile's binary | Note |", "|---|---|---|---|", *rows, ""]
        decoders = ffmpeg.get("decoders", [])
        lines += [f"FFmpeg decoders compiled in: {', '.join(decoders) if decoders else 'none'}.", ""]
        extra = [f"{k}: {', '.join(ffmpeg[k])}" for k in ("demuxers", "muxers", "encoders") if ffmpeg.get(k)]
        if extra:
            lines += ["Other components: " + "; ".join(extra) + ".", ""]
    lines += ["## Third-party libraries and their licences", "",
              "See `third_party/NOTICES.md` (generated into `MediaEngine.acknowledgements`): FFmpeg LGPL-2.1-or-later (dynamic), dav1d BSD-2-Clause (extended variant), libass ISC, FreeType FTL (a credit line is required), HarfBuzz MIT, FriBidi LGPL-2.1-or-later (dynamic, replaceable). No GPL or non-free component is linked; `scripts/check-licenses.sh` fails the build if one appears.", ""]
    return "\n".join(lines), problems


def main():
    content, problems = build(load())
    if problems:
        sys.exit("\n".join(problems))
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == content else 1)
    OUT.write_text(content)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
