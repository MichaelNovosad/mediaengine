#!/bin/bash
# Links the static subtitle libraries (libass, FreeType, HarfBuzz, FriBidi) of every slice into ONE dynamic framework
# (LibASS), then bundles the five slices into build/LibASS.xcframework.
# usage: scripts/package-subtitle-xcframework.sh
# Dynamic linking keeps the LGPL promise for FriBidi: a customer can replace the framework with their own build.
source "$(dirname "$0")/lib/common.sh"

FW="LibASS"
BUNDLE_ID="dev.mediaengine.LibASS"   # placeholder until the product name is chosen (D-E6)
version="$(lock_field libass 2)"
out="$BUILD/frameworks-subs"
rm -rf "$out" "$BUILD/dsyms-subs" "$BUILD/$FW.xcframework"; mkdir -p "$out" "$BUILD/dsyms-subs"

plist() { # <slice> → Info.plist on stdout
  local platform minkey
  case "$1" in
    macos) platform=MacOSX; minkey=LSMinimumSystemVersion ;;
    ios) platform=iPhoneOS; minkey=MinimumOSVersion ;;
    ios-simulator) platform=iPhoneSimulator; minkey=MinimumOSVersion ;;
    xros) platform=XROS; minkey=MinimumOSVersion ;;
    xros-simulator) platform=XRSimulator; minkey=MinimumOSVersion ;;
  esac
  cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleDevelopmentRegion</key><string>en</string>
  <key>CFBundleExecutable</key><string>$FW</string>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>CFBundleName</key><string>$FW</string>
  <key>CFBundlePackageType</key><string>FMWK</string>
  <key>CFBundleShortVersionString</key><string>$version</string>
  <key>CFBundleVersion</key><string>$version</string>
  <key>CFBundleSupportedPlatforms</key><array><string>$platform</string></array>
  <key>$minkey</key><string>$MIN_OS</string>
</dict></plist>
EOF
}

privacy() {
  cat <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>NSPrivacyTracking</key><false/>
  <key>NSPrivacyTrackingDomains</key><array/>
  <key>NSPrivacyCollectedDataTypes</key><array/>
  <key>NSPrivacyAccessedAPITypes</key><array/>
</dict></plist>
EOF
}

make_framework() {
  local slice="$1"
  local inst="$BUILD/install/subs-$slice"
  [ -d "$inst" ] || die "missing $inst (run scripts/build-subtitle-libs.sh $slice)"
  local target sysroot sdk cc fwdir content res install_name
  target="$(slice_target "$slice")"; sysroot="$(slice_sysroot "$slice")"; sdk="$(slice_sdk "$slice")"
  cc="$(xcrun --sdk "$sdk" --find clang)"
  fwdir="$out/$slice/$FW.framework"
  if [ "$slice" = "macos" ]; then
    content="$fwdir/Versions/A"; res="$content/Resources"; install_name="@rpath/$FW.framework/Versions/A/$FW"
  else
    content="$fwdir"; res="$fwdir"; install_name="@rpath/$FW.framework/$FW"
  fi
  mkdir -p "$content/Headers/ass" "$content/Modules" "$res/licenses"

  # Only libass's own API leaves the framework; FreeType, HarfBuzz and FriBidi stay inside.
  local exports="$BUILD/work/exports-subs.txt"
  mkdir -p "$BUILD/work"; printf '_ass_*\n' > "$exports"

  log "link $FW for $slice"
  "$cc" -dynamiclib -target "$target" -isysroot "$sysroot" \
    -install_name "$install_name" -compatibility_version 1.0.0 -current_version "$version" \
    -Wl,-force_load,"$inst/lib/libass.a" -Wl,-force_load,"$inst/lib/libfreetype.a" \
    -Wl,-force_load,"$inst/lib/libharfbuzz.a" -Wl,-force_load,"$inst/lib/libfribidi.a" -Wl,-force_load,"$inst/lib/libunibreak.a" \
    -Wl,-exported_symbols_list,"$exports" \
    -framework CoreText -framework CoreFoundation -framework CoreGraphics -lc++ -liconv \
    -o "$content/$FW"

  cp "$inst/include/ass/ass.h" "$inst/include/ass/ass_types.h" "$content/Headers/ass/"
  {
    echo "// Generated by scripts/package-subtitle-xcframework.sh. libass $version (ISC); FreeType, HarfBuzz and FriBidi are linked inside."
    echo "#include <$FW/ass/ass_types.h>"
    echo "#include <$FW/ass/ass.h>"
  } > "$content/Headers/$FW.h"
  sed -E -i '' 's|#[[:space:]]*include[[:space:]]+"ass_types.h"|#include <'"$FW"'/ass/ass_types.h>|' "$content/Headers/ass/ass.h"
  printf 'framework module %s {\n    umbrella header "%s.h"\n    export *\n}\n' "$FW" "$FW" > "$content/Modules/module.modulemap"
  cp "$inst"/licenses/* "$res/licenses/"
  plist "$slice" > "$res/Info.plist"
  privacy > "$res/PrivacyInfo.xcprivacy"

  if [ "$slice" = "macos" ]; then
    ln -sfn A "$fwdir/Versions/Current"
    ln -sfn "Versions/Current/$FW" "$fwdir/$FW"
    for d in Headers Modules Resources; do ln -sfn "Versions/Current/$d" "$fwdir/$d"; done
  fi

  mkdir -p "$BUILD/dsyms-subs/$slice"
  dsymutil "$content/$FW" -o "$BUILD/dsyms-subs/$slice/$FW.framework.dSYM" 2>/dev/null || true
  strip -x "$content/$FW"
  codesign --force --sign - --timestamp=none "$fwdir" >/dev/null
}

for s in $SLICES; do make_framework "$s"; done

# Smoke test: the module imports cleanly in Objective-C (macOS slice).
log "module smoke test"
printf '@import LibASS;\nint main(void){ return ass_library_version() > 0 ? 0 : 1; }\n' > "$BUILD/work/smoke-subs.m"
xcrun --sdk macosx clang -fmodules -fsyntax-only -Werror=incomplete-umbrella -F "$out/macos" "$BUILD/work/smoke-subs.m"

log "create xcframework"
args=""
for s in $SLICES; do args="$args -framework $out/$s/$FW.framework"; done
# shellcheck disable=SC2086
xcodebuild -create-xcframework $args -output "$BUILD/$FW.xcframework" | tail -2
log "done: $BUILD/$FW.xcframework"
